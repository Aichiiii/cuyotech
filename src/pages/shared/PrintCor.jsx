import { useNavigate, useParams } from 'react-router-dom';
import { ArrowLeft, Printer } from 'lucide-react';
import { Button, ErrorAlert, Loading } from '../../components/ui';
import { fmtDate, fmtDateTime, peso, useApi, yearLevel } from '../../utils';
import logo from '../../assets/logo-crest.png';

export function PaperHead() {
  return (
    <div className="paper-head">
      <img src={logo} alt="CuyoTech University seal" />
      <div className="republic">Republic of the Philippines</div>
      <div className="school">CUYOTECH UNIVERSITY</div>
      <div className="address">City of Cabuyao, Laguna, Philippines 4025</div>
    </div>
  );
}

export default function PrintCor() {
  const { id } = useParams();
  const navigate = useNavigate();
  const { data, error, loading } = useApi(`/print/cor/${id}`);

  return (
    <div className="print-page">
      <div className="print-toolbar">
        <Button onClick={() => navigate(-1)}><ArrowLeft /> Back</Button>
        <Button variant="primary" onClick={() => window.print()} disabled={!data}><Printer /> Print / Save as PDF</Button>
      </div>
      {loading ? <Loading /> : error ? <div className="paper"><ErrorAlert error={error} /></div> : (
        <div className="paper">
          <PaperHead />
          <div className="paper-title">Certificate of Registration</div>
          <div className="grid grid-2 mb-4">
            <dl className="info-list">
              <dt>COR No.</dt><dd className="mono">{data.enrollment.cor_number}</dd>
              <dt>Student No.</dt><dd>{data.student.student_number}</dd>
              <dt>Name</dt><dd>{data.student_name}</dd>
            </dl>
            <dl className="info-list">
              <dt>Term</dt><dd>{data.enrollment.semester} Semester, SY {data.enrollment.school_year}</dd>
              <dt>Program</dt><dd>{data.student.program_code} — {yearLevel(data.student.year_level)}</dd>
              <dt>Department</dt><dd>{data.student.department_name}</dd>
            </dl>
          </div>

          <table className="table">
            <thead><tr><th>Code</th><th>Subject</th><th>Section</th><th className="num">Units</th></tr></thead>
            <tbody>
              {data.subjects.map((s) => (
                <tr key={s.enrollment_subject_id}><td>{s.course_code}</td><td>{s.course_name}</td><td>{s.section_code}</td><td className="num">{s.units}</td></tr>
              ))}
            </tbody>
            <tfoot><tr><td colSpan={3}>Total units</td><td className="num">{data.fees.units}</td></tr></tfoot>
          </table>

          <table className="table mt-4">
            <thead><tr><th>Assessment</th><th className="num">Rate</th><th className="num">Qty</th><th className="num">Amount</th></tr></thead>
            <tbody>
              {data.fees.lines.map((f) => (
                <tr key={f.fee_name}><td>{f.fee_name}</td><td className="num">{peso(f.amount)}</td><td className="num">{f.quantity}</td><td className="num">{peso(f.subtotal)}</td></tr>
              ))}
            </tbody>
            <tfoot>
              <tr><td colSpan={3}>Total assessment</td><td className="num">{peso(data.fees.total)}</td></tr>
              <tr><td colSpan={3}>Payment status</td><td className="num">{data.payment.state}{data.payment.payment?.receipt_number ? ` (${data.payment.payment.receipt_number})` : ''}</td></tr>
            </tfoot>
          </table>

          <div className="signature">
            <div>
              <strong>{data.enrollment.finalized_by_name}</strong><br />University Registrar<br />
              <span className="text-xs">Finalized {fmtDateTime(data.enrollment.finalized_at)}</span>
            </div>
          </div>
          <div className="paper-foot">System-generated by CuyoTech SSIS on {fmtDate(new Date().toISOString())}. Verify authenticity with the Office of the University Registrar using the COR number.</div>
        </div>
      )}
    </div>
  );
}
